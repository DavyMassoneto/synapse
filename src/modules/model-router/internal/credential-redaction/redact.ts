import {
  ROUTER_CREDENTIAL_PATTERN,
  ROUTER_CREDENTIAL_REMOVED,
  ROUTER_NAMED_SECRET_PATTERN,
  ROUTER_NAMED_SECRET_REMOVED,
  ROUTER_PRIVATE_KEY_PATTERN,
  ROUTER_PRIVATE_KEY_REMOVED,
  ROUTER_VAULT_PATTERN,
  ROUTER_VAULT_REMOVED,
} from "./constants"

export function redactRouterCredentials(text: string): string {
  return text
    .replace(ROUTER_PRIVATE_KEY_PATTERN, ROUTER_PRIVATE_KEY_REMOVED)
    .replace(ROUTER_CREDENTIAL_PATTERN, ROUTER_CREDENTIAL_REMOVED)
    .replace(ROUTER_NAMED_SECRET_PATTERN, ROUTER_NAMED_SECRET_REMOVED)
    .replace(ROUTER_VAULT_PATTERN, ROUTER_VAULT_REMOVED)
}

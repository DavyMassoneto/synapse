import {
  COMPUTER_DRIVER_RELEASE_CURRENT_DIRECTORY,
  COMPUTER_DRIVER_RELEASE_FOREIGN_PATH_SEPARATOR,
  COMPUTER_DRIVER_RELEASE_PARENT_DIRECTORY,
  COMPUTER_DRIVER_RELEASE_PATH_SEPARATOR,
} from "./constants"

export function isDriverReleaseChecksumName(name: string): boolean {
  return (
    !name.includes(COMPUTER_DRIVER_RELEASE_PATH_SEPARATOR) &&
    !name.includes(COMPUTER_DRIVER_RELEASE_FOREIGN_PATH_SEPARATOR) &&
    name !== COMPUTER_DRIVER_RELEASE_CURRENT_DIRECTORY &&
    name !== COMPUTER_DRIVER_RELEASE_PARENT_DIRECTORY
  )
}
